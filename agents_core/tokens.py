"""
agents_core.tokens
===================

Оценка числа токенов без обращения к конкретному токенизатору провайдера.

Точные значения prompt_tokens/completion_tokens/total_tokens для уже
выполненного запроса всегда берутся из ответа самого провайдера (поле
usage у DeepSeek, prompt_eval_count/eval_count у Ollama) и сохраняются в
БД как есть — эта функция используется только для *предварительной*
оценки (например, чтобы прикинуть текущий размер контекста ещё до того,
как отправлено хотя бы одно сообщение, или чтобы проверить условие
автосуммаризации по числу токенов до фактического вызова LLM).
"""

from __future__ import annotations

#: Грубая эвристика: около 4 символов на токен для большинства современных
#: BPE-токенизаторов на латинице/кириллице. Это приближение, а не точный
#: подсчёт — используется только там, где нет точных данных из ответа API.
_CHARS_PER_TOKEN = 4


def estimate_tokens(text: str) -> int:
    if not text:
        return 0
    return max(1, (len(text) + _CHARS_PER_TOKEN - 1) // _CHARS_PER_TOKEN)


def estimate_messages_tokens(texts) -> int:
    """Оценка суммарного числа токенов для последовательности строк
    (например system_prompt + содержимое истории сообщений)."""
    return sum(estimate_tokens(t) for t in texts if t)
